"""把实验结果导出成可以直接粘进报告的表格（Markdown + LaTeX / booktabs）。T2

输出：
    reports/tables/table1_datasets.md/.tex      数据集体量
    reports/tables/table2_d1_results.md/.tex    D1 全部 33 行
    reports/tables/table3_d2_results.md/.tex    D2 全部 33 行
    reports/tables/table4_delta.md/.tex         与论文的 Δaccuracy 汇总
    reports/tables/table5_efficiency.md/.tex    效率（需要先跑 T3；没有则标注 pending）

用法：
    python -m analysis.export_tables            # 生成全部
    python -m analysis.export_tables --check    # 生成后逐格核对 leaderboard.csv

约束：所有数字读自 results/leaderboard.csv、results/efficiency.csv、splits/*.csv；
      论文值读自 leaderboard.csv 的 paper_acc / paper_f1 列（源头是 docs/paper_results.csv）。
"""

from __future__ import annotations

import argparse
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
SPLITS = ROOT / "splits"
OUT = ROOT / "reports" / "tables"

DISPLAY = {
    "vgg16": "VGG16", "vgg19": "VGG19", "resnet50": "ResNet50", "resnet101": "ResNet101",
    "inception_resnet_v2": "InceptionResNetV2", "xception": "Xception",
    "mobilenet_v2": "MobileNetV2", "efficientnet_b0": "EfficientNet-B0",
    "efficientnet_b7": "EfficientNet-B7", "efficientnet_v2m": "EfficientNetV2-M",
    "nasnet_large": "NASNet-Large",
}
ORDER = ["vgg16", "vgg19", "resnet50", "resnet101", "inception_resnet_v2", "xception",
         "mobilenet_v2", "efficientnet_b0", "efficientnet_b7", "efficientnet_v2m", "nasnet_large"]
OPT_LABEL = {"adam": "Adam", "sgd": "SGD", "rmsprop": "RMSprop"}


# ---------------------------------------------------------------- io helpers
def read_csv(path: Path) -> list[dict]:
    with path.open(encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh))


def fnum(v, default=None):
    try:
        return float(v)
    except (TypeError, ValueError):
        return default


def model_order(rows: list[dict]) -> list[str]:
    present = {r["model"] for r in rows}
    return [m for m in ORDER if m in present] + sorted(present - set(ORDER))


# ---------------------------------------------------------------- renderers
def to_markdown(title: str, header: list[str], rows: list[list[str]], note: str = "") -> str:
    out = [f"### {title}", ""]
    out.append("| " + " | ".join(header) + " |")
    out.append("|" + "|".join("---" if i else "---" for i in range(len(header))) + "|")
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    if note:
        out += ["", note]
    out.append("")
    return "\n".join(out)


def tex_cell(value) -> str:
    """LaTeX 单元格转义：千分位逗号转 \\, 其余特殊字符转义。"""
    s = str(value)
    if re.fullmatch(r"\d{1,3}(,\d{3})+", s):
        return s.replace(",", "\\,")
    return (s.replace("\\", "\\textbackslash{}")
             .replace("&", "\\&").replace("%", "\\%")
             .replace("_", "\\_").replace("#", "\\#"))


def to_latex(title: str, label: str, header: list[str], rows: list[list[str]],
             note: str = "", align: str | None = None) -> str:
    n = len(header)
    align = align or ("l" + "r" * (n - 1))
    lines = [
        "% generated by analysis/export_tables.py — do not edit by hand",
        "\\begin{table}[htbp]",
        "  \\centering",
        "  \\caption{" + title + "}",
        "  \\label{" + label + "}",
        "  \\small",
        "  \\begin{tabular}{" + align + "}",
        "    \\toprule",
        "    " + " & ".join(tex_cell(h) for h in header) + " \\\\",
        "    \\midrule",
    ]
    for r in rows:
        lines.append("    " + " & ".join(tex_cell(c) for c in r) + " \\\\")
    lines += [
        "    \\bottomrule",
        "  \\end{tabular}",
    ]
    if note:
        lines.append("  \\par\\vspace{2pt}{\\footnotesize " + note + "}")
    lines += ["\\end{table}", ""]
    return "\n".join(lines)


def write_pair(stem: str, title: str, label: str, header: list[str], rows: list[list[str]],
               note_md: str = "", note_tex: str = "", align: str | None = None) -> None:
    (OUT / f"{stem}.md").write_text(to_markdown(title, header, rows, note_md), encoding="utf-8")
    (OUT / f"{stem}.tex").write_text(to_latex(title, label, header, rows, note_tex, align),
                                     encoding="utf-8")


# ---------------------------------------------------------------- tables
def table1(rows: list[dict]) -> None:
    """Table 1 — 数据集体量（计数直接来自 splits/*.csv）。"""
    body = []
    for ds, resolution, source in [("D1", "5184×3456", "Original photographs"),
                                   ("D2", "128×128", "Authors' augmented set")]:
        p = SPLITS / f"{ds}.csv"
        if not p.exists():
            continue
        sp = read_csv(p)
        counts = {"defect": 0, "nondefect": 0}
        by_split = {"train": 0, "val": 0, "test": 0}
        for r in sp:
            counts[r["label"]] = counts.get(r["label"], 0) + 1
            by_split[r["split"]] = by_split.get(r["split"], 0) + 1
        body.append([ds, str(counts["defect"]), str(counts["nondefect"]),
                     str(len(sp)), str(by_split["train"]), str(by_split["val"]),
                     str(by_split["test"]), resolution, source])
    write_pair("table1_datasets", "Table 1 — Dataset composition (stratified 70/10/20 split, seed 42)",
               "tab:datasets",
               ["Dataset", "Defect", "Non-defect", "Total", "Train", "Val", "Test",
                "Original resolution", "Source"],
               body,
               note_md="> D2 is the authors' augmented version of D1 (segmentation provenance lost); "
                       "the third dataset used in the paper (1,557 images) is not public.",
               note_tex="D2 is the authors' augmented version of D1; the paper's third dataset (1,557 images) is not public.",
               align="lrrrrrrll")


def results_table(rows: list[dict], ds: str, number: str, stem: str) -> None:
    body = []
    for m in model_order(rows):
        for opt in ("adam", "sgd", "rmsprop"):
            r = next((x for x in rows if x["model"] == m and x["dataset"] == ds
                      and x["optimizer"] == opt), None)
            if not r:
                continue
            body.append([
                DISPLAY.get(m, m), OPT_LABEL[opt],
                f"{fnum(r['accuracy']):.4f}", f"{fnum(r['precision']):.4f}",
                f"{fnum(r['recall']):.4f}", f"{fnum(r['f1']):.4f}",
                f"{fnum(r['mcc']):.4f}", f"{fnum(r['auc']):.4f}", f"{fnum(r['map']):.4f}",
                f"{int(fnum(r['n_params_trainable'])):,}",
                f"{fnum(r['train_time_s']):.1f}",
            ])
    write_pair(stem, f"Table {number} — {ds} results (33 runs, seed 42)", f"tab:{ds.lower()}",
               ["Model", "Opt.", "Acc.", "Prec.", "Rec.", "F1", "MCC", "AUC", "mAP",
                "Trainable params", "Time (s)"],
               body,
               note_md=f"> {ds}: positive class = defect. Test n = {meta_n_test(ds)}. "
                       "Params = trainable classification head only.",
               note_tex=f"{ds}: positive class = defect, test n = {meta_n_test(ds)}; "
                        "trainable parameters refer to the classification head only.",
               align="llrrrrrrrrr")


def meta_n_test(ds: str) -> str:
    vals = []
    for p in (RESULTS / "runs").glob(f"*__{ds}__*"):
        m = p / "metrics.json"
        if not m.exists():
            continue
        txt = m.read_text(encoding="utf-8")
        hit = re.search(r'"n_test":\s*(\d+)', txt)
        if hit:
            vals.append(int(hit.group(1)))
    return f"{min(vals)}–{max(vals)}" if vals and min(vals) != max(vals) else (str(vals[0]) if vals else "?")


def table4(rows: list[dict]) -> None:
    """Table 4 — 与论文的 Δaccuracy（同一优化器 Adam 对齐）。"""
    body = []
    for m in model_order(rows):
        cells = [DISPLAY.get(m, m)]
        for ds in ("D1", "D2"):
            r = next((x for x in rows if x["model"] == m and x["dataset"] == ds
                      and x["optimizer"] == "adam"), None)
            if not r:
                cells += ["—", "—", "—"]
                continue
            ours = fnum(r["accuracy"])
            paper = fnum(r["paper_acc"])
            delta = fnum(r["delta_acc"])
            cells += [f"{ours:.4f}", f"{paper:.4f}" if paper is not None else "—",
                      f"{delta:+.4f}" if delta is not None else "—"]
        r = next((x for x in rows if x["model"] == m and x["dataset"] == "D1"
                  and x["optimizer"] == "adam"), None)
        cells.append("collapsed$^{*}$" if r and fnum(r["paper_f1"]) == 0 else "")
        body.append(cells)
    write_pair("table4_delta", "Table 4 — Reproduction gap versus reported values (Adam runs)",
               "tab:delta",
               ["Model", "D1 ours", "D1 reported", "Δ D1", "D2 ours", "D2 reported", "Δ D2", "Note"],
               body,
               note_md="> $^{*}$ Authors' reported F1 = 0.000 (all samples predicted as the majority class), "
                       "so the large Δ is a collapsed run on their side, not evidence of a better implementation.",
               note_tex="$^{*}$Authors' reported F1 = 0.000 (majority-class collapse); the large gap reflects a failed run, "
                        "not a better implementation.",
               align="lrrrrrrl")


